/** Rota inicial de cada contexto (primeira entrada permitida do menu). */
export const CONTEXT_HOME: Record<RouteContext, string> = {
  rd: '/visao-geral',
  establishment: '/unidade',
  advertiser: '/anunciante',
}

export function routeById(id: string): AppRoute | undefined {
  return ROUTES.find((r) => r.id === id)
}

export function canAccessRoute(route: AppRoute, permissions: readonly string[] | undefined): boolean {
  return route.permission === null || (!!permissions && permissions.includes(route.permission))
}

/** Itens de menu visíveis para o contexto e permissões atuais. */
export function visibleNavRoutes(context: RouteContext | null, permissions: readonly string[] | undefined): AppRoute[] {
  if (!context) return []
  return ROUTES.filter((r) => r.nav && r.contexts.includes(context) && canAccessRoute(r, permissions))
}

/** Primeira rota acessível no contexto (para o redirecionamento de "/"). */
export function firstAccessiblePath(context: RouteContext | null, permissions: readonly string[] | undefined): string {
  const nav = visibleNavRoutes(context, permissions).filter((r) => r.nav?.section !== 'conta')
  if (context && nav.some((r) => r.path === CONTEXT_HOME[context])) return CONTEXT_HOME[context]
  return nav[0]?.path ?? '/minha-conta'
}
